const EXTRA_ON: Record<string, string[]> = {
  lynk10ev: ["lynk10plus"],
  "xingyue-l-hev": ["xingyue-l"],
  "xingrui-s": ["xingrui"],
  "7x": ["7x-hk"],
  x: ["x-hk"],
  "009": ["009-hk"],
};

export function brochureFor(id: string): BrochureIntel[] {
  const brand = BROCHURE_BRAND[id];
  const catalog = BROCHURE[id] || BROCHURE_MORE[id];
  const extras = (EXTRA_ON[id] || [])
    .map((k) => BROCHURE_BRAND[k] || BROCHURE[k] || BROCHURE_MORE[k])
    .filter(Boolean) as BrochureIntel[];
  const list: BrochureIntel[] = [];
  const push = (b?: BrochureIntel) => {
    if (!b) return;
    if (list.some((x) => x.url === b.url && x.title === b.title)) return;
    list.push(b);
  };
  push(brand);
  if (catalog) {
    const superseded = Boolean(brand) && brand.source !== "海外产品手册";
    if (!superseded) push(catalog);
  }
  extras.forEach(push);
  return list;
}

export function brochureManuals(id: string) {
  return brochureFor(id).map((b) => ({
    title: b.title,
    url: b.url,
    kind: (b.source === "海外产品手册" ? "overseas" : b.source === "官网产品手册" ? "brochure" : "config") as
      | "overseas"
      | "brochure"
      | "config",
  }));
}
